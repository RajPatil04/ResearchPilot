"""Export and dossier formatting utilities for ResearchPilot AI."""

from __future__ import annotations

import re
from datetime import datetime
from typing import Any, Dict, List, Optional, Tuple


def sanitize_filename(name: str, max_length: int = 50) -> str:
    """Produces safe, cross-platform filenames without illegal characters."""
    clean = re.sub(r'[\\/*?:"<>|]', "", name)
    clean = re.sub(r"\s+", "_", clean).strip("_")
    if not clean:
        clean = "research_paper"
    return clean[:max_length]


def _build_header(doc_type: str, title: str, metadata: Optional[Dict[str, Any]] = None) -> str:
    """Generates standard metadata header for exports."""
    now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    pages = metadata.get("page_count", "N/A") if metadata else "N/A"
    filename = metadata.get("filename", "N/A") if metadata else "N/A"

    return f"""# {doc_type}: {title}

**Generated by:** ResearchPilot AI (Powered by Gemma 4)  
**Date:** {now}  
**Source Document:** `{filename}`  
**Document Pages:** {pages}  

---
"""


def export_summary_markdown(
    title: str,
    summary_content: str,
    metadata: Optional[Dict[str, Any]] = None
) -> Tuple[str, str]:
    """Generates a downloadable Markdown summary with frontmatter."""
    header = _build_header("Research Summary", title, metadata)
    full_md = f"{header}\n{summary_content.strip()}\n"
    date_str = datetime.now().strftime("%Y%m%d")
    filename = f"ResearchPilot_Summary_{sanitize_filename(title)}_{date_str}.md"
    return full_md, filename


def export_chat_markdown(
    title: str,
    chat_history: List[Dict[str, str]],
    metadata: Optional[Dict[str, Any]] = None
) -> Tuple[str, str]:
    """Formats interactive Q&A session transcripts as Markdown."""
    header = _build_header("Q&A Notes & Dialogue", title, metadata)
    turns = []
    for idx, turn in enumerate(chat_history, 1):
        role = turn.get("role", "user").capitalize()
        content = turn.get("content", "").strip()
        icon = "👤" if role == "User" else "🔬"
        turns.append(f"### Turn {idx} — {icon} {role}\n\n{content}\n")

    body = "\n---\n\n".join(turns) if turns else "*No conversation recorded in this session.*"
    full_md = f"{header}\n{body}\n"
    date_str = datetime.now().strftime("%Y%m%d")
    filename = f"ResearchPilot_Chat_{sanitize_filename(title)}_{date_str}.md"
    return full_md, filename


def export_insights_markdown(
    title: str,
    insights_content: str,
    metadata: Optional[Dict[str, Any]] = None
) -> Tuple[str, str]:
    """Formats research opportunities, limitations, and future work as Markdown."""
    header = _build_header("Research Insights & Opportunities Report", title, metadata)
    full_md = f"{header}\n{insights_content.strip()}\n"
    date_str = datetime.now().strftime("%Y%m%d")
    filename = f"ResearchPilot_Insights_{sanitize_filename(title)}_{date_str}.md"
    return full_md, filename


def export_figure_analysis_markdown(
    title: str,
    page_number: int,
    question: str,
    analysis_content: str,
    metadata: Optional[Dict[str, Any]] = None
) -> Tuple[str, str]:
    """Formats multimodal figure / diagram analysis."""
    header = _build_header(f"Figure Analysis (Page {page_number})", title, metadata)
    body = f"""### Analyzed Query
> **{question}**

### Visual Inspection Findings
{analysis_content.strip()}
"""
    full_md = f"{header}\n{body}\n"
    date_str = datetime.now().strftime("%Y%m%d")
    filename = f"ResearchPilot_Figure_P{page_number}_{sanitize_filename(title)}_{date_str}.md"
    return full_md, filename


def export_complete_dossier_markdown(
    title: str,
    metadata: Optional[Dict[str, Any]] = None,
    summary: Optional[str] = None,
    chat_history: Optional[List[Dict[str, str]]] = None,
    insights: Optional[str] = None,
    figure_notes: Optional[List[Dict[str, Any]]] = None,
    agent_reports: Optional[List[Dict[str, Any]]] = None
) -> Tuple[str, str]:
    """Combines all generated research artifacts into an all-in-one comprehensive research dossier."""
    header = _build_header("Complete Research Dossier", title, metadata)
    sections = [header]

    if summary and summary.strip():
        sections.append("## 📑 1. Structured Paper Summary\n\n" + summary.strip())

    if insights and insights.strip():
        sections.append("## 🧭 2. Research Insights, Limitations & Directions\n\n" + insights.strip())

    if figure_notes:
        fig_chunks = ["## 🖼️ 3. Visual & Figure Analysis Records"]
        for f in figure_notes:
            fig_chunks.append(
                f"### Page {f.get('page', '?')} Analysis\n"
                f"**Question:** {f.get('question', '')}\n\n"
                f"{f.get('analysis', '')}\n"
            )
        sections.append("\n\n".join(fig_chunks))

    if agent_reports:
        agent_chunks = ["## 🤖 4. Autonomous Agent Investigation Traces"]
        for ar in agent_reports:
            agent_chunks.append(
                f"### Inquiry: {ar.get('query', '')}\n"
                f"**Tool Steps:** {ar.get('tool_calls_count', 0)}\n\n"
                f"{ar.get('synthesized_answer', '')}\n"
            )
        sections.append("\n\n".join(agent_chunks))

    if chat_history:
        chat_chunks = ["## 💬 5. Dialogue & Q&A Transcript"]
        for idx, turn in enumerate(chat_history, 1):
            role = turn.get("role", "user").capitalize()
            chat_chunks.append(f"**{role}:** {turn.get('content', '')}")
        sections.append("\n\n".join(chat_chunks))

    full_md = "\n\n---\n\n".join(sections)
    date_str = datetime.now().strftime("%Y%m%d")
    filename = f"ResearchPilot_Full_Dossier_{sanitize_filename(title)}_{date_str}.md"
    return full_md, filename
